"""Build the public source catalogue from the publisher's GeoJSON and mosaic metadata.

Usage: python scripts/build-soviet-coverage.py DIRECTORY > styles/soviet-coverage.mjs
Place the releases' bounds.geojson and Soviet-GS-<scale>.mosaic.json in
DIRECTORY/<scale>/. No raster imagery is read or stored.
"""
import base64
import json
import math
from pathlib import Path
import re
import sys

GRID = 128
root = Path(sys.argv[1])


def bounds(feature):
    ring = feature["geometry"]["coordinates"][0]
    xs, ys = zip(*ring)
    return [min(xs), min(ys), max(xs), max(ys)]


def grid_point(lon, lat):
    latitude = math.radians(max(-85.05112878, min(85.05112878, lat)))
    xy = [(lon + 180) / 360, (1 - math.asinh(math.tan(latitude)) / math.pi) / 2]
    return [max(0, min(GRID - 1, math.floor(v * GRID))) for v in xy]


series = {}
for key in ["1m", "500k", "200k", "100k", "50k", "25k"]:
    directory = root / key
    manifest = json.loads((directory / f"Soviet-GS-{key}.mosaic.json").read_text())
    index = json.loads((directory / "bounds.geojson").read_text())
    cells = bytearray(GRID * GRID // 8)
    excluded = []
    for sheet in index["features"]:
        west, south, east, north = bounds(sheet)
        years = [int(y) for y in re.findall(r"\d{4}", str(sheet["properties"].get("year", "")))]
        if not years or min(years) < 1922 or max(years) > 1991:
            excluded.append([west, south, east, north])
            continue
        left, top = grid_point(west, north)
        right, bottom = grid_point(east, south)
        for y in range(top, bottom + 1):
            for x in range(left, right + 1):
                cell = y * GRID + x
                cells[cell // 8] |= 1 << (cell % 8)
    header = manifest["header"]
    series[key] = {
        "maxzoom": header["max_zoom"],
        "bounds": [header[k + "_e7"] / 1e7 for k in ("min_lon", "min_lat", "max_lon", "max_lat")],
        "cells": base64.b64encode(cells).decode(),
        "excluded": excluded,
    }
print("// Generated by scripts/build-soviet-coverage.py from the Indian Open Maps sheet registers.")
print("export const gridSize =", GRID, ";")
print("export const series =", json.dumps(series, separators=(",", ":")), ";")
