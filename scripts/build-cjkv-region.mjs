// Maintenance build only: derive the CJKV label region from Natural Earth
// 1:10m admin-0 countries (public domain, de facto boundaries).
// Usage: node scripts/build-cjkv-region.mjs [ne_10m_admin_0_countries.geojson]
import {readFile, writeFile} from 'node:fs/promises';
const SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries.geojson';
// Areas that historically write with Han characters.
const CJKV = ['CHN','TWN','HKG','MAC','JPN','KOR','PRK','VNM'];
// Coasts are simplified to about 1 km. Land borders keep full detail: border
// towns such as Heihe and Blagoveshchensk face each other across one river.
const TOLERANCE = 0.01; // degrees
const input = process.argv[2];
const world = JSON.parse(input ? await readFile(input,'utf8') : await (await fetch(SOURCE)).text());
const rings = f => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates).flat(1);
const key = ([x,y]) => `${x.toFixed(6)},${y.toFixed(6)}`;
// Vertices shared with a non-CJKV country are land borders. Only coastal
// edges receive the tolerance buffer for reclaimed land and simplification.
const foreign = new Set();
for (const f of world.features) if (!CJKV.includes(f.properties.ADM0_A3)) for (const ring of rings(f)) for (const p of ring) foreign.add(key(p));
function simplify(points) {
  if (points.length < 3) return points;
  const keep = new Uint8Array(points.length); keep[0] = keep[points.length-1] = 1;
  const stack = [[0, points.length-1]];
  while (stack.length) {
    const [a,b] = stack.pop(); const [ax,ay] = points[a], [bx,by] = points[b];
    const dx = bx-ax, dy = by-ay, len = Math.hypot(dx,dy);
    let max = 0, index = -1;
    for (let i = a+1; i < b; i++) {
      const [px,py] = points[i];
      const d = len ? Math.abs(dy*px - dx*py + bx*ay - by*ax)/len : Math.hypot(px-ax,py-ay);
      if (d > max) { max = d; index = i; }
    }
    if (max > TOLERANCE) { keep[index] = 1; stack.push([a,index],[index,b]); }
  }
  return points.filter((_,i)=>keep[i]);
}
const polygons = [], borders = [];
for (const f of world.features.filter(f=>CJKV.includes(f.properties.ADM0_A3))) for (const ring of rings(f)) {
  // Split each ring into border and coast runs, then simplify each run while
  // keeping run endpoints, so the classification survives simplification.
  const runs = [];
  for (let i = 0; i < ring.length-1; i++) {
    const border = foreign.has(key(ring[i])) && foreign.has(key(ring[i+1]));
    if (!runs.length || runs.at(-1).border !== border) runs.push({border, points:[ring[i]]});
    runs.at(-1).points.push(ring[i+1]);
  }
  const simplified = runs.map(run => ({...run, points: run.border ? run.points : simplify(run.points)}));
  const outline = simplified.flatMap((run,i) => i ? run.points.slice(1) : run.points);
  polygons.push(outline);
  for (const run of simplified) if (run.border) borders.push(run.points);
}
// Delta encoding in 1e-3 degree integers keeps the module compact.
const encode = line => { let px = 0, py = 0; return line.flatMap(([x,y]) => { const X = Math.round(x*1000), Y = Math.round(y*1000), d = [X-px, Y-py]; px = X; py = Y; return d; }); };
const count = lines => lines.reduce((s,l)=>s+l.length,0);
console.log(`Polygons ${polygons.length} (${count(polygons)} points), borders ${borders.length} (${count(borders)} points)`);
await writeFile(new URL('../styles/cjkv-region-data.mjs', import.meta.url),
  `// Generated by scripts/build-cjkv-region.mjs from Natural Earth 1:10m admin-0\n// countries (public domain): ${CJKV.join(', ')}. Delta-encoded 1e-3 degrees.\n` +
  `export const POLYGONS = ${JSON.stringify(polygons.map(encode))};\n` +
  `export const BORDERS = ${JSON.stringify(borders.map(encode))};\n`);
