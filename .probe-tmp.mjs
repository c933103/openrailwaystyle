import {chromium} from 'playwright';
import {readFile} from 'node:fs/promises';
const browser = await chromium.launch({executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader']});
const ctx = await browser.newContext({viewport: {width: 1100, height: 750}, ignoreHTTPSErrors: true});
const local = {'maplibre-gl.js': 'application/javascript', 'maplibre-gl.css': 'text/css', 'pmtiles.js': 'application/javascript'};
await ctx.route(/cdn\.jsdelivr\.net\/npm\/(maplibre-gl|pmtiles)@/, async route => { const name = route.request().url().split('/').pop(); route.fulfill({body: await readFile(`/tmp/claude-0/${name}`), contentType: local[name], headers: {'access-control-allow-origin': '*'}}); });
const page = await ctx.newPage();
await page.goto('http://127.0.0.1:4173/?v=z&autoGlobe=0#5/36.5/138', {waitUntil: 'domcontentloaded'});
await page.waitForSelector('body[data-map-ready="true"]', {state: 'attached', timeout: 90000});
await page.waitForTimeout(15000);
const r = await page.evaluate(async () => {
  const {map} = await import(document.querySelector('script[type="module"]').src);
  const src = map.querySourceFeatures('openmaptiles', {sourceLayer: 'place'}).filter(f => ['country','province','state'].includes(f.properties.class)).slice(0, 4).map(f => ({c: f.properties.class, n: f.properties.name, atlas: f.properties.atlas_name, iso: f.properties.iso_a2}));
  const rendered = map.queryRenderedFeatures({layers: ['country_label', 'country_label-other', 'place_label_other', 'place_label_city'].filter(id => map.getLayer(id))}).slice(0, 8).map(f => [f.layer.id, f.properties.class, f.properties.name]);
  const layer = map.getStyle().layers.find(l => l.id === 'country_label');
  return {src, rendered, vis: map.getLayoutProperty('country_label', 'visibility'), tf: JSON.stringify(layer.layout['text-field']).slice(0, 300), zoom: map.getZoom()};
});
console.log(JSON.stringify(r, null, 1));
await page.screenshot({path: '/tmp/claude-0/z5.png'});
await browser.close();
