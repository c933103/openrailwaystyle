import test from 'node:test';
import assert from 'node:assert/strict';
import {cp, mkdir, mkdtemp, readFile, readdir, rm, writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {sourceCopyOptions} from './helpers/source-copy.mjs';

async function fixture(t) {
  const root = await mkdtemp(join(tmpdir(), 'atlas-source-copy-'));
  t.after(() => rm(root, {recursive: true, force: true}));
  const source = join(root, 'scripts'), target = join(root, 'copy');
  const files = {
    'build.mjs': 'export const answer = 42;\n',
    'helper.py': 'answer = 42\n',
    'nested/fixture.json': '{"answer":42}\n',
    'nested/__pycache__notes.mjs': 'export const keep = true;\n',
    '__pycache__/helper.cpython-312.pyc': 'generated bytecode',
    '__pycache__/helper.cpython-312.pyc.123': 'unfinished bytecode',
    'nested/__pycache__/other.cpython-312.pyc': 'nested bytecode',
  };
  for (const [name, content] of Object.entries(files)) {
    await mkdir(join(source, name, '..'), {recursive: true});
    await writeFile(join(source, name), content);
  }
  return {root, source, target, files};
}

test('source fixtures preserve real inputs but never traverse Python cache directories', async t => {
  const {source, target, files} = await fixture(t);
  await cp(source, target, sourceCopyOptions);
  const expected = Object.keys(files).filter(name => !name.split('/').includes('__pycache__'));
  for (const name of expected) assert.equal(await readFile(join(target, name), 'utf8'), files[name]);
  assert.deepEqual((await readdir(target, {recursive: true})).sort(), [...expected, 'nested'].sort());
});

test('a disappearing Python temporary reproduces the old failure and cannot race filtered copying', async t => {
  const {root, source, target} = await fixture(t);
  const temporary = join(source, '__pycache__/helper.cpython-312.pyc.123');
  const disappear = async src => {
    if (src === temporary) await rm(src);
    return true;
  };
  // Deterministically remove the bytecode temporary after traversal sees it,
  // just as Python's atomic bytecode rename can do during parallel tests.
  await assert.rejects(cp(source, join(root, 'unfiltered'), {recursive: true, filter: disappear}), {code: 'ENOENT'});
  await writeFile(temporary, 'new unfinished bytecode');
  let touchedTemporary = false;
  await cp(source, target, {...sourceCopyOptions, filter: async src => {
    if (!sourceCopyOptions.filter(src)) return false;
    if (src === temporary) touchedTemporary = true;
    return disappear(src);
  }});
  assert.equal(touchedTemporary, false);
  assert.equal(await readFile(join(target, 'helper.py'), 'utf8'), 'answer = 42\n');
  await assert.rejects(readFile(join(target, '__pycache__/helper.cpython-312.pyc.123')), {code: 'ENOENT'});
});

test('a missing real source still fails rather than silently producing a partial fixture', async t => {
  const {source, target} = await fixture(t);
  const real = join(source, 'build.mjs');
  await assert.rejects(cp(source, target, {...sourceCopyOptions, filter: async src => {
    if (!sourceCopyOptions.filter(src)) return false;
    if (src === real) await rm(src);
    return true;
  }}), {code: 'ENOENT'});
});
